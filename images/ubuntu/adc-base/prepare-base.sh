#!/bin/bash -e
################################################################################
##  File:  prepare-base.sh
##  Desc:  Prepare an ADC build sandbox base with systemd, SSH and Dev Tunnels
################################################################################

set -euo pipefail

export DEBIAN_FRONTEND=noninteractive
apt-get update --error-on=any
apt-get install -y --no-install-recommends \
    ca-certificates curl dbus jq libicu-dev openssh-server sudo systemd systemd-sysv

curl --fail --silent --show-error --location --retry 3 \
    https://aka.ms/TunnelsCliDownload/linux-x64 -o /usr/local/bin/devtunnel
chmod 755 /usr/local/bin/devtunnel
devtunnel --version
sha256sum /usr/local/bin/devtunnel

mkdir -p /etc/ssh/sshd_config.d /etc/systemd/system/ssh.service.d
cat > /etc/ssh/sshd_config.d/00-adc.conf <<'EOF'
PermitRootLogin prohibit-password
PasswordAuthentication no
KbdInteractiveAuthentication no
PubkeyAuthentication yes
EOF

# Generate host identities at boot, never share the keys generated by apt.
cat > /etc/systemd/system/ssh.service.d/host-keys.conf <<'EOF'
[Service]
RuntimeDirectory=sshd
RuntimeDirectoryMode=0755
ExecStartPre=
ExecStartPre=/usr/bin/ssh-keygen -A
ExecStartPre=/usr/sbin/sshd -t
EOF
rm -f /etc/ssh/ssh_host_*_key /etc/ssh/ssh_host_*_key.pub
systemctl disable ssh.socket
systemctl enable ssh.service
systemctl mask systemd-modules-load.service tmp.mount

apt-get clean
rm -rf /var/lib/apt/lists/*
